const fs = require('node:fs');
const path = require('node:path');
const postcss = require('postcss');
const root = path.resolve(__dirname, '..');
// Order is a compatibility contract: later rules intentionally override earlier components.
const styleSources = Object.freeze([
  'src/styles/base.css',
  'src/styles/simulator.css',
  'src/styles/catalog.css',
  'src/styles/responsive.css',
  'src/styles/navigation.css',
  'src/styles/layout.css',
  'src/styles/curriculum.css',
  'src/styles/shell.css',
  'src/styles/curriculum-overrides.css',
  'src/styles/feedback.css',
]);
function compileStyles() {
  const contents = styleSources.map((file) => fs.readFileSync(path.join(root, file), 'utf8').trim());
  const stylesheet =
    '/* Generated by scripts/styles.cjs. Edit src/styles/ instead. */\n\n' + contents.join('\n\n') + '\n';
  postcss.parse(stylesheet);
  return stylesheet;
}
module.exports = { styleSources, compileStyles };
